#!/usr/bin/env python3
"""Write lib/core/push/firebase_config.dart from the Firebase client config files.

  Android: android/app/google-services.json        (package com.nguyenanhdh.quangbinh)
  iOS:     ios/Runner/GoogleService-Info.plist      (bundle  com.savinapower.nguyenanhapp)

Usage: python3 tool/firebase_config_from_json.py [android.json] [ios.plist]
Either file may be missing; that platform is then simply "push off".
"""
import json
import plistlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ANDROID_PACKAGE = "com.nguyenanhdh.quangbinh"
IOS_BUNDLE = "com.savinapower.nguyenanhapp"


def q(v: str) -> str:
    return "'" + v.replace("\\", "\\\\").replace("'", "\\'") + "'"


def android(path: Path):
    if not path.exists():
        return None
    j = json.loads(path.read_text())
    info = j["project_info"]
    c = next((c for c in j["client"] if c["client_info"]["android_client_info"]["package_name"] == ANDROID_PACKAGE), None)
    if c is None:
        sys.exit(f"No Android app '{ANDROID_PACKAGE}' in {path}")
    return {
        "apiKey": c["api_key"][0]["current_key"],
        "appId": c["client_info"]["mobilesdk_app_id"],
        "messagingSenderId": info["project_number"],
        "projectId": info["project_id"],
        "storageBucket": info.get("storage_bucket"),
    }


def ios(path: Path):
    if not path.exists():
        return None
    p = plistlib.loads(path.read_bytes())
    if p.get("BUNDLE_ID") != IOS_BUNDLE:
        sys.exit(f"{path} is for bundle '{p.get('BUNDLE_ID')}', expected '{IOS_BUNDLE}'")
    return {
        "apiKey": p["API_KEY"],
        "appId": p["GOOGLE_APP_ID"],
        "messagingSenderId": p["GCM_SENDER_ID"],
        "projectId": p["PROJECT_ID"],
        "storageBucket": p.get("STORAGE_BUCKET"),
        "iosBundleId": p["BUNDLE_ID"],
    }


def dart(name: str, o) -> str:
    if o is None:
        return f"const FirebaseOptions? {name} = null;\n"
    lines = [f"const FirebaseOptions? {name} = FirebaseOptions("]
    for k in ("apiKey", "appId", "messagingSenderId", "projectId", "storageBucket", "iosBundleId"):
        if o.get(k):
            lines.append(f"  {k}: {q(o[k])},")
    lines.append(");\n")
    return "\n".join(lines)


def main() -> None:
    a = android(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "android/app/google-services.json")
    i = ios(Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "ios/Runner/GoogleService-Info.plist")
    out = ROOT / "lib/core/push/firebase_config.dart"
    out.write_text(
        "import 'package:firebase_core/firebase_core.dart';\n\n"
        "/// Firebase client config of the app — generated by tool/firebase_config_from_json.py from\n"
        "/// android/app/google-services.json and ios/Runner/GoogleService-Info.plist. Do not edit by hand.\n"
        "/// A null value = push is off on that platform.\n"
        + dart("kFirebaseAndroidOptions", a)
        + "\n"
        + dart("kFirebaseIosOptions", i)
    )
    print(f"wrote {out} (android={'yes' if a else 'no'}, ios={'yes' if i else 'no'})")


if __name__ == "__main__":
    main()
